#!/usr/bin/env python3
"""Generate SYNTHETIC DEMO GIS layers for a Pinpoint 311 instance.

Nothing this script writes is an official record. Every feature carries
`"demo": true`, every layer name starts with "Demo — " and every description
says "Synthetic demo data, not official records". Owner names are obviously
fictional ("DEMO OWNER 0412"); street names are the town's real ones (from
`road_segments`) with made-up house numbers.

What it builds, all inside the township boundary in system settings and laid
out along the real road centrelines in `road_segments`:

  * parcels.geojson       ~1,000-1,500 tax-parcel polygons fronting residential
                          streets in a few neighbourhoods, NJ MOD-IV style fields
                          (PAMS_PIN, BLOCK, LOT, PROP_CLASS, values, zoning...)
  * trash_zones.geojson   four large trash-pickup zones (polygons)
  * storm_drains.geojson  catch basins / inlets along the curb (points)
  * hydrants.geojson      fire hydrants (points)
  * streetlights.geojson  streetlights (points)
  * street_signs.geojson  regulatory / warning / guide signs (points)
  * manifest.json         the layer settings load_demo_gis.py applies

Deterministic: a fixed seed, and every query is ordered, so the same road data
gives byte-identical output. Geometry is computed by PostGIS (parcels) and in
plain Python on a local metric projection (points); the database is only read.

Town-specific inputs (neighbourhood centres, municipal code, counts) come from
a JSON file passed with --config; the format is in configure(). Keep that file
with the instance, not in this repository.

Run inside the instance's backend container (it uses the app's DB settings):

    docker cp backend/scripts/. <stack>-backend-1:/tmp/demo-gis-scripts/
    docker cp demo-gis-config.json <stack>-backend-1:/tmp/demo-gis-config.json
    docker exec -w /app <stack>-backend-1 python /tmp/demo-gis-scripts/generate_demo_gis.py \\
        --config /tmp/demo-gis-config.json --out /tmp/demo-gis

See docs/DEMO_DATA.md.
"""

