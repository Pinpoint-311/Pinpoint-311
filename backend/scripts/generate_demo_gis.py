def street_abbr(name: str) -> str:
    words = name.split()
    if words and words[-1] in STREET_ABBR:
        words[-1] = STREET_ABBR[words[-1]]
    return " ".join(words).upper()


def date_between(rng: random.Random, y0: int, y1: int) -> str:
    return f"{rng.randint(y0, y1):04d}-{rng.randint(1, 12):02d}-{rng.randint(1, 28):02d}"


def weighted(rng: random.Random, options: Sequence[Tuple[Any, float]]) -> Any:
    total = sum(w for _, w in options)
    x = rng.random() * total
    for value, w in options:
        x -= w
        if x <= 0:
            return value
    return options[-1][0]


def fc(features: List[Dict[str, Any]], title: str) -> Dict[str, Any]:
    return {"type": "FeatureCollection", "name": title, "demo": True, "notice": NOTICE,
            "features": features}


def point_feature(lnglat: List[float], props: Dict[str, Any]) -> Dict[str, Any]:
    return {"type": "Feature", "geometry": {"type": "Point", "coordinates": lnglat},
            "properties": {**props, "demo": True}}


def sample(rng: random.Random, items: List[Any], n: int) -> List[Any]:
    """`n` of `items`, keeping their order."""
    if len(items) <= n:
        return items
    keep = set(rng.sample(range(len(items)), n))
    return [it for k, it in enumerate(items) if k in keep]


