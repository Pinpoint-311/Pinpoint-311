def _engine():
    from sqlalchemy import create_engine
    from app.core.config import get_settings
    url = get_settings().database_url.replace("postgresql+asyncpg://", "postgresql://")
    return create_engine(url)


def boundary_geometry(conn) -> Dict[str, Any]:
    from sqlalchemy import text
    raw = conn.execute(text("SELECT township_boundary FROM system_settings ORDER BY id LIMIT 1")).scalar()
    if isinstance(raw, str):
        raw = json.loads(raw)
    if not raw:
        sys.exit("No township boundary in system settings.")
    if raw.get("type") == "FeatureCollection":
        geoms = [f["geometry"] for f in raw.get("features") or [] if f.get("geometry")]
        if len(geoms) != 1:
            sys.exit("Expected one boundary polygon, found %d." % len(geoms))
        return geoms[0]
    if raw.get("type") == "Feature":
        return raw["geometry"]
    return raw


def _hood_values_sql() -> Tuple[str, Dict[str, Any]]:
    rows, params = [], {}
    for n, h in enumerate(NEIGHBORHOODS):
        rows.append(f"(:h{n}, :lat{n}, :lng{n}, :r{n}, :f{n}, :d{n})")
        params.update({f"h{n}": h["hid"], f"lat{n}": h["lat"], f"lng{n}": h["lng"],
                       f"r{n}": float(h["radius"]), f"f{n}": float(h["frontage"]),
                       f"d{n}": float(h["depth"])})
    return "VALUES " + ", ".join(rows), params


def parcel_geometries(conn, boundary: Dict[str, Any]) -> List[Dict[str, Any]]:
    """Lots fronting residential streets, made non-overlapping, clipped to the boundary.

    Each named residential segment is cut into equal frontages on both sides;
    each lot is the strip between SETBACK_M and SETBACK_M + depth from the
    centreline (single-sided flat-ended buffers). Then every lot loses
    whatever any road's ROAD_CLEAR_M buffer or any lower-ranked lot covers, so
    corner lots come out notched and back-to-back lots share a rear line.
    """
    from sqlalchemy import text
    hoods, params = _hood_values_sql()
    params["bnd"] = json.dumps(boundary)
    params.update(setback=SETBACK_M, clear=ROAD_CLEAR_M, min_area=MIN_LOT_M2)
    conn.execute(text("DROP TABLE IF EXISTS demo_cand"))
    conn.execute(text(f"""
        CREATE TEMP TABLE demo_cand AS
        WITH h(hid, lat, lng, radius, frontage, depth) AS ({hoods}),
        hc AS (SELECT h.*, ST_Transform(ST_SetSRID(ST_MakePoint(lng, lat), 4326), {SRID}) c FROM h),
        roads AS (
            -- Collector roads (S1200) get wider, deeper lots than residential streets.
            SELECT DISTINCT ON (r.source_feature_id) hc.hid, hc.c, hc.radius,
                   CASE WHEN r.highway_class = 'S1200' THEN hc.frontage * 1.4 ELSE hc.frontage END AS frontage,
                   CASE WHEN r.highway_class = 'S1200' THEN hc.depth * 1.25 ELSE hc.depth END AS depth,
                   r.highway_class AS cls, r.source_feature_id AS sfid, r.name, ST_Transform(r.geom, {SRID}) AS g
            FROM hc JOIN road_segments r
              ON ST_DWithin(ST_Transform(r.geom, {SRID}), hc.c, hc.radius)
            WHERE r.highway_class IN ('S1200', 'S1400') AND r.name IS NOT NULL
              AND r.name <> 'Unnamed Segment'
            ORDER BY r.source_feature_id, hc.hid
        ),
        cuts AS (
            SELECT roads.*, s.side, n.n, i
            FROM roads, (VALUES ('left'), ('right')) s(side),
                 LATERAL (SELECT floor(ST_Length(g) / frontage)::int AS n) n,
                 LATERAL generate_series(0, n.n - 1) i
        )
        SELECT row_number() OVER (ORDER BY hid, sfid, side, i) AS rk,
               hid, cls, sfid, name, side, i, n, c, radius,
               ST_Difference(
                   ST_Buffer(sub, :setback + depth + ((i * 7 + length(side)) % 5) * 2,
                             'side=' || side || ' endcap=flat join=mitre'),
                   ST_Buffer(sub, :setback, 'side=' || side || ' endcap=flat join=mitre')) AS g0
        FROM cuts, LATERAL ST_LineSubstring(g, i::float / n, (i + 1)::float / n) sub
    """), params)
    conn.execute(text("CREATE INDEX ON demo_cand USING gist (g0)"))
    conn.execute(text("ANALYZE demo_cand"))
    rows = conn.execute(text(f"""
        WITH bnd AS (SELECT ST_Transform(ST_SetSRID(ST_GeomFromGeoJSON(:bnd), 4326), {SRID}) AS g),
        rb AS (
            SELECT ST_Buffer(ST_Transform(r.geom, {SRID}), :clear) AS g
            FROM road_segments r
            WHERE ST_Transform(r.geom, {SRID}) && (SELECT ST_Expand(ST_Extent(g0), 50) FROM demo_cand)
        ),
        trimmed AS (
            SELECT c.rk, c.hid, c.cls, c.sfid, c.name, c.side, c.i, c.c, c.radius,
                   ST_Intersection(
                       ST_Difference(
                           ST_Difference(c.g0, COALESCE(
                               (SELECT ST_Union(rb.g) FROM rb WHERE ST_Intersects(rb.g, c.g0)),
                               ST_SetSRID('GEOMETRYCOLLECTION EMPTY'::geometry, {SRID}))),
                           COALESCE((SELECT ST_Union(o.g0) FROM demo_cand o
                                     WHERE o.rk < c.rk AND ST_Intersects(o.g0, c.g0)
                                       AND ST_Area(ST_Intersection(o.g0, c.g0)) > 0.5),
                                    ST_SetSRID('GEOMETRYCOLLECTION EMPTY'::geometry, {SRID}))),
                       (SELECT g FROM bnd)) AS g
            FROM demo_cand c
        ),
        part AS (
            SELECT DISTINCT ON (t.rk) t.*, d.geom AS pg
            FROM trimmed t, LATERAL ST_Dump(ST_CollectionExtract(ST_MakeValid(t.g), 3)) d
            ORDER BY t.rk, ST_Area(d.geom) DESC
        ),
        kept AS (
            SELECT * FROM part
            WHERE ST_Area(pg) >= :min_area
              AND 4 * pi() * ST_Area(pg) / (ST_Perimeter(pg) ^ 2) >= 0.25
              AND ST_DWithin(ST_Centroid(pg), c, radius)
        ),
        -- To WGS 84 on a 1e-7 degree grid (what 7 decimals can say), repaired
        -- after the snap so the file is valid exactly as written.
        out AS (
            SELECT DISTINCT ON (k.rk) k.rk, k.hid, k.cls, k.sfid, k.name, k.side, k.i,
                   ST_Area(k.pg) AS area_m2, d.geom AS wg
            FROM kept k, LATERAL ST_Dump(ST_CollectionExtract(ST_MakeValid(ST_SnapToGrid(
                     ST_Transform(ST_SimplifyPreserveTopology(k.pg, 0.05), 4326), 0.0000001)), 3)) d
            ORDER BY k.rk, ST_Area(d.geom) DESC
        )
        SELECT rk, hid, cls, sfid, name, side, i, area_m2, ST_AsGeoJSON(wg, 7) AS gj
        FROM out ORDER BY rk
    """), params).mappings().all()
    conn.execute(text("DROP TABLE IF EXISTS demo_cand"))
    return [dict(r) for r in rows]


def trash_zone_geometries(conn, boundary: Dict[str, Any]) -> List[Dict[str, Any]]:
    """The boundary cut into four quadrants about its centroid."""
    from sqlalchemy import text
    rows = conn.execute(text("""
        WITH b AS (SELECT ST_SetSRID(ST_GeomFromGeoJSON(:bnd), 4326) AS g),
        c AS (SELECT ST_X(ST_Centroid(g)) AS x, ST_Y(ST_Centroid(g)) AS y,
                     ST_XMin(g) - 0.01 AS x0, ST_YMin(g) - 0.01 AS y0,
                     ST_XMax(g) + 0.01 AS x1, ST_YMax(g) + 0.01 AS y1 FROM b),
        q(k, w, s, e, n) AS (
            SELECT 'NW', x0, y, x, y1 FROM c UNION ALL
            SELECT 'NE', x, y, x1, y1 FROM c UNION ALL
            SELECT 'SW', x0, y0, x, y FROM c UNION ALL
            SELECT 'SE', x, y0, x1, y FROM c)
        SELECT q.k, ST_AsGeoJSON(ST_SimplifyPreserveTopology(
                   ST_CollectionExtract(ST_Intersection(b.g, ST_MakeEnvelope(w, s, e, n, 4326)), 3),
                   0.00005), 6) AS gj
        FROM q, b ORDER BY q.k
    """), {"bnd": json.dumps(boundary)}).mappings().all()
    return [dict(r) for r in rows]


def road_lines(conn) -> List[Dict[str, Any]]:
    """Road centrelines (4326) inside the asset area, ordered."""
    from sqlalchemy import text
    hoods, params = _hood_values_sql()
    params["extra"] = ASSET_EXTRA_M
    rows = conn.execute(text(f"""
        WITH h(hid, lat, lng, radius, frontage, depth) AS ({hoods}),
        area AS (SELECT ST_Transform(ST_Union(ST_Buffer(
                     ST_Transform(ST_SetSRID(ST_MakePoint(lng, lat), 4326), {SRID}), radius + :extra)), 4326) AS g
                 FROM h)
        SELECT r.source_feature_id AS sfid, COALESCE(NULLIF(r.name, ''), 'Unnamed Segment') AS name,
               r.highway_class AS cls, d.path[1] AS part, ST_AsGeoJSON(d.geom, 7) AS gj
        FROM road_segments r, area,
             LATERAL ST_Dump(ST_CollectionExtract(ST_Intersection(r.geom, area.g), 2)) d
        WHERE ST_Intersects(r.geom, area.g)
          AND r.highway_class IN ('S1100', 'S1200', 'S1400')
        ORDER BY r.source_feature_id, d.path[1]
    """), params).mappings().all()
    out = []
    for r in rows:
        coords = json.loads(r["gj"])["coordinates"]
        if len(coords) >= 2:
            out.append({"sfid": r["sfid"], "name": r["name"], "cls": r["cls"],
                        "part": r["part"] or 0, "coords": coords})
    return out


# ---------------------------------------------------------------------------
# Plane geometry on a local projection (metres about a fixed origin)
# ---------------------------------------------------------------------------

class Local:
    def __init__(self, lat0: float, lng0: float):
        self.lat0, self.lng0 = lat0, lng0
        self.kx = 111_320.0 * math.cos(math.radians(lat0))
        self.ky = 110_574.0

    def fwd(self, lng: float, lat: float) -> Tuple[float, float]:
        return (lng - self.lng0) * self.kx, (lat - self.lat0) * self.ky

    def inv(self, x: float, y: float) -> List[float]:
        return [round(self.lng0 + x / self.kx, 7), round(self.lat0 + y / self.ky, 7)]


def line_length(pts: Sequence[Tuple[float, float]]) -> float:
    return sum(math.dist(pts[k], pts[k + 1]) for k in range(len(pts) - 1))


def point_along(pts: Sequence[Tuple[float, float]], d: float) -> Tuple[float, float, float, float]:
    """(x, y, ux, uy): the point `d` metres along and the unit tangent there."""
    run = 0.0
    for k in range(len(pts) - 1):
        (x0, y0), (x1, y1) = pts[k], pts[k + 1]
        seg = math.dist(pts[k], pts[k + 1])
        if seg == 0:
            continue
        if run + seg >= d or k == len(pts) - 2:
            t = max(0.0, min(1.0, (d - run) / seg))
            return x0 + (x1 - x0) * t, y0 + (y1 - y0) * t, (x1 - x0) / seg, (y1 - y0) / seg
        run += seg
    (x0, y0), (x1, y1) = pts[0], pts[-1]
    seg = math.dist(pts[0], pts[-1]) or 1.0
    return x0, y0, (x1 - x0) / seg, (y1 - y0) / seg


def offset(x: float, y: float, ux: float, uy: float, side: int, dist: float) -> Tuple[float, float]:
    """side +1 = left of travel direction, -1 = right."""
    return x - uy * dist * side, y + ux * dist * side


def _ring_contains(ring: Sequence[Sequence[float]], x: float, y: float) -> bool:
    inside = False
    j = len(ring) - 1
    for i in range(len(ring)):
        xi, yi = ring[i][0], ring[i][1]
        xj, yj = ring[j][0], ring[j][1]
        if (yi > y) != (yj > y) and x < (xj - xi) * (y - yi) / ((yj - yi) or 1e-15) + xi:
            inside = not inside
        j = i
    return inside


def in_boundary(geom: Dict[str, Any], lng: float, lat: float) -> bool:
    polys = geom["coordinates"] if geom["type"] == "MultiPolygon" else [geom["coordinates"]]
    for poly in polys:
        if _ring_contains(poly[0], lng, lat) and not any(_ring_contains(h, lng, lat) for h in poly[1:]):
            return True
    return False


