def build_signs(lines, local, boundary) -> List[Dict[str, Any]]:
    """Signs at real intersections (where differently named roads meet) and mid-block."""
    rng = random.Random(SEED + 5)
    ends: Dict[Tuple[int, int], List[Tuple[Dict[str, Any], int]]] = {}
    projected = []
    for ln in lines:
        pts = [local.fwd(c[0], c[1]) for c in ln["coords"]]
        projected.append((ln, pts))
        for which in (0, -1):
            x, y = pts[which]
            ends.setdefault((int(round(x / 4)), int(round(y / 4))), []).append((ln, which))
    rank = {"S1100": 0, "S1200": 1, "S1400": 2}
    cands = []
    for key in sorted(ends):
        approaches = ends[key]
        names = sorted({a[0]["name"] for a in approaches})
        if len(names) < 2:
            continue
        top = min(rank.get(a[0]["cls"], 3) for a in approaches)
        first_name = True
        for ln, which in approaches:
            pts = [local.fwd(c[0], c[1]) for c in ln["coords"]]
            if which == 0:
                pts = pts[::-1]
            length = line_length(pts)
            if length < 25:
                continue
            x, y, ux, uy = point_along(pts, length - 10)  # 10 m before the corner
            px, py = offset(x, y, ux, uy, -1, 6.0)          # on the right
            minor = rank.get(ln["cls"], 3) > top or (rank.get(ln["cls"], 3) == top
                                                      and ln["name"] != names[0])
            if minor:
                cands.append({"xy": (px, py), "line": ln, "code": "R1-1" if rng.random() < 0.9 else "R1-2"})
            if first_name:
                qx, qy = offset(x, y, ux, uy, -1, 8.0)
                cands.append({"xy": (qx, qy), "line": ln, "code": "D3-1"})
                first_name = False
    for ln, pts in projected:
        length = line_length(pts)
        if length > 300:
            x, y, ux, uy = point_along(pts, length * 0.5)
            px, py = offset(x, y, ux, uy, -1, 6.0)
            code = weighted(rng, [("R2-1", 0.5), ("W1-2", 0.2), ("W11-2", 0.15), ("R7-1", 0.15)])
            cands.append({"xy": (px, py), "line": ln, "code": code})
    cands = [c for c in _thin(cands, 6) if in_boundary(boundary, *local.inv(*c["xy"]))]
    cands = sample(rng, cands, TARGETS["signs"])
    feats = []
    for n, c in enumerate(cands, start=1):
        sign_type, message = SIGN_TYPES[c["code"]]
        if c["code"] == "D3-1":
            message = c["line"]["name"]
        feats.append(point_feature(local.inv(*c["xy"]), {
            "asset_id": f"SIGN-{n:04d}",
            "asset_type": "street_sign",
            "STREET": c["line"]["name"],
            "MUTCD_CODE": c["code"],
            "SIGN_TYPE": sign_type,
            "MESSAGE": message,
            "INSTALL_YEAR": rng.randint(1995, 2025),
            # Retroreflectivity against the MUTCD minimums (Table 2A-3).
            "RETRO_RATING": weighted(rng, [("Pass", 0.75), ("Marginal", 0.17), ("Fail", 0.08)]),
            "POST_TYPE": weighted(rng, [("U-channel steel", 0.7), ("Square tube steel", 0.2),
                                        ("Wood", 0.1)]),
        }))
    return feats


