PROP_CLASSES = [("2", 0.86), ("1", 0.05), ("4A", 0.03), ("4C", 0.01), ("15C", 0.03), ("15D", 0.02)]
# Lots on collector roads: more commercial, apartments and public uses.
PROP_CLASSES_COLLECTOR = [("2", 0.55), ("1", 0.08), ("4A", 0.2), ("4C", 0.05), ("15C", 0.07),
                          ("15D", 0.05)]


def build_parcels(rows: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    rng = random.Random(SEED + 1)
    hoods = {h["hid"]: h for h in NEIGHBORHOODS}
    block_of: Dict[Tuple[int, str, str], str] = {}
    next_block: Dict[int, int] = {}
    lot_no: Dict[str, int] = {}
    street_seg: Dict[str, Dict[str, int]] = {}
    seen_pins = set()
    features = []
    for n, r in enumerate(rows, start=1):
        h = hoods[r["hid"]]
        key = (r["hid"], r["sfid"], r["side"])
        if key not in block_of:
            next_block[r["hid"]] = next_block.get(r["hid"], h["block_base"]) + 1
            block_of[key] = str(next_block[r["hid"]])
        block = block_of[key]
        lot_no[block] = lot_no.get(block, 0) + 1
        lot = str(lot_no[block])
        pin = f"{MUN_CODE}_{block}_{lot}"
        if pin in seen_pins:  # cannot happen, but the ID must be unique
            continue
        seen_pins.add(pin)

        segs = street_seg.setdefault(r["name"], {})
        seg_idx = segs.setdefault(r["sfid"], len(segs))
        house = 100 * (seg_idx + 1) + 2 * r["i"] + (1 if r["side"] == "left" else 2)

        acreage = round(r["area_m2"] / 4046.856, 3)
        cls = weighted(rng, PROP_CLASSES_COLLECTOR if r["cls"] == "S1200" else PROP_CLASSES)
        y0, y1 = h["years"]
        land = int(round((55_000 + acreage * 420_000 + rng.randint(-8_000, 12_000)) / 100.0) * 100)
        year_built: Optional[int] = rng.randint(y0, y1)
        if cls == "1":
            improvement, year_built = 0, None
        elif cls == "2":
            improvement = int(round(rng.randint(95_000, 340_000) / 100.0) * 100)
        elif cls in ("4A", "4C"):
            land = int(land * 1.6)
            improvement = int(round(rng.randint(220_000, 900_000) / 100.0) * 100)
        else:  # 15C public, 15D church/charitable
            improvement = int(round(rng.randint(0, 450_000) / 100.0) * 100)
            if improvement == 0:
                year_built = None
        zoning = {"4A": "HC-D", "4C": "RM-D", "15C": "PF-D", "15D": "PF-D"}.get(cls, h["zoning"])
        owner = ("DEMO PUBLIC ENTITY (FICTIONAL)" if cls == "15C"
                 else "DEMO CONGREGATION (FICTIONAL)" if cls == "15D"
                 else f"DEMO OWNER {n:04d} (FICTIONAL)")
        props = {
            "PAMS_PIN": pin,
            "PCL_MUN": MUN_CODE,
            "MUN_NAME": MUN_NAME,
            "COUNTY": COUNTY,
            "BLOCK": block,
            "LOT": lot,
            "QUAL": "",
            "PROP_LOC": f"{house} {street_abbr(r['name'])}",
            "PROP_CLASS": cls,
            "LAND_VAL": land,
            "IMPRVT_VAL": improvement,
            "NET_VALUE": land + improvement,
            "ACREAGE": acreage,
            "ZONING": zoning,
            "YEAR_BUILT": year_built,
            "OWNER_NAME": owner,
            "demo": True,
        }
        features.append({"type": "Feature", "geometry": json.loads(r["gj"]), "properties": props})
    return features


def build_trash_zones(rows: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    spec = {
        "NW": ("TZ-1", "Zone 1 (north-west)", "Monday", "A"),
        "NE": ("TZ-2", "Zone 2 (north-east)", "Tuesday", "B"),
        "SW": ("TZ-3", "Zone 3 (south-west)", "Thursday", "A"),
        "SE": ("TZ-4", "Zone 4 (south-east)", "Friday", "B"),
    }
    out = []
    for r in rows:
        zid, label, day, week = spec[r["k"]]
        out.append({"type": "Feature", "geometry": json.loads(r["gj"]), "properties": {
            "ZONE_ID": zid, "ZONE_LABEL": f"Demo {label}", "TRASH_DAY": day,
            "RECYCLING_WEEK": f"Week {week}", "BULK_PICKUP": "First " + day + " of the month",
            "demo": True}})
    return out


def _walk(lines, local, spacing_for, off_m, alternate=True, start_frac=0.5):
    """Candidate (line, distance, point, tangent, side) along each line."""
    out = []
    for li, ln in enumerate(lines):
        spacing = spacing_for(ln)
        if not spacing:
            continue
        pts = [local.fwd(c[0], c[1]) for c in ln["coords"]]
        length = line_length(pts)
        k = 0
        d = spacing * start_frac
        while d < length - 3:
            x, y, ux, uy = point_along(pts, d)
            side = (1 if k % 2 == 0 else -1) if alternate else -1
            px, py = offset(x, y, ux, uy, side, off_m)
            out.append({"line": ln, "d": d, "xy": (px, py), "side": side, "k": k})
            k += 1
            d += spacing
    return out


def _thin(cands, min_gap):
    """Drop candidates within `min_gap` m of one already kept (segment joins)."""
    kept, grid = [], {}
    cell = max(min_gap, 1.0)
    for c in cands:
        x, y = c["xy"]
        gx, gy = int(x // cell), int(y // cell)
        near = False
        for ix in (gx - 1, gx, gx + 1):
            for iy in (gy - 1, gy, gy + 1):
                for ox, oy in grid.get((ix, iy), ()):
                    if math.hypot(x - ox, y - oy) < min_gap:
                        near = True
        if not near:
            grid.setdefault((gx, gy), []).append((x, y))
            kept.append(c)
    return kept


def build_drains(lines, local, boundary) -> List[Dict[str, Any]]:
    rng = random.Random(SEED + 2)
    cands = _walk(lines, local, lambda ln: 95 if ln["cls"] == "S1400" else 70, 5.5)
