MUN_CODE = "0000"        # NJ MOD-IV municipal code, the prefix of a PAMS_PIN
MUN_NAME = "DEMO TOWN"
COUNTY = "DEMO"
SRID = 0                 # metric CRS for the parcel geometry; UTM zone of the first centre
NEIGHBORHOODS: List[Dict[str, Any]] = []
SETBACK_M = 8.0          # road centreline to the front lot line
ROAD_CLEAR_M = 7.0       # every road is kept clear of lots by this much
MIN_LOT_M2 = 250.0
ASSET_EXTRA_M = 600.0    # point assets cover the neighbourhoods plus this ring
# Target counts per point layer (the candidate set is sampled down to these).
TARGETS = {"drains": 480, "hydrants": 300, "lights": 450, "signs": 300}

_HOOD_KEYS = ("lat", "lng", "radius", "frontage", "depth", "zoning", "years")


def configure(cfg: Dict[str, Any]) -> None:
    """Apply a config dict. Raises SystemExit with a readable message when it is wrong.

    {
      "seed": 311,
      "municipality": {"code": "0000", "name": "DEMO TWP", "county": "DEMO"},
      "neighborhoods": [
        {"lat": 40.0, "lng": -74.5, "radius": 500, "frontage": 25, "depth": 40,
         "zoning": "R-75", "years": [1965, 2010], "block_base": 100}
      ],
      "targets": {"drains": 480, "hydrants": 300, "lights": 450, "signs": 300},
      "asset_extra_m": 600
    }
    """
    global SEED, MUN_CODE, MUN_NAME, COUNTY, SRID, NEIGHBORHOODS, TARGETS, ASSET_EXTRA_M
    hoods = cfg.get("neighborhoods") or []
    if not hoods:
        sys.exit("config: `neighborhoods` must list at least one centre.")
    out = []
    for n, h in enumerate(hoods, start=1):
        missing = [k for k in _HOOD_KEYS if k not in h]
        if missing:
            sys.exit(f"config: neighbourhood {n} is missing {', '.join(missing)}.")
        out.append({**h, "hid": n, "years": tuple(h["years"]),
                    "block_base": int(h.get("block_base", n * 300 - 200))})
    NEIGHBORHOODS = out
    muni = cfg.get("municipality") or {}
    MUN_CODE = str(muni.get("code", MUN_CODE))
    MUN_NAME = str(muni.get("name", MUN_NAME)).upper()
    COUNTY = str(muni.get("county", COUNTY)).upper()
    SEED = int(cfg.get("seed", SEED))
    TARGETS = {**TARGETS, **(cfg.get("targets") or {})}
    ASSET_EXTRA_M = float(cfg.get("asset_extra_m", ASSET_EXTRA_M))
    lat, lng = out[0]["lat"], out[0]["lng"]
    zone = int((lng + 180) // 6) + 1
    SRID = int(cfg.get("srid") or ((32600 if lat >= 0 else 32700) + zone))


