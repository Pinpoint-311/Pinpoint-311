def main(argv: Optional[List[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--config", required=True,
                    help="JSON file with the town's parameters (see configure())")
    ap.add_argument("--out", required=True, help="directory to write the GeoJSON files into")
    args = ap.parse_args(argv)
    configure(json.loads(Path(args.config).read_text(encoding="utf-8")))
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)

    engine = _engine()
    with engine.connect() as conn:
        boundary = boundary_geometry(conn)
        parcel_rows = parcel_geometries(conn, boundary)
        zone_rows = trash_zone_geometries(conn, boundary)
        lines = road_lines(conn)
        conn.rollback()
    engine.dispose()

    h0 = NEIGHBORHOODS[0]
    local = Local(h0["lat"], h0["lng"])
    layers = {
        "parcels": (build_parcels(parcel_rows), "parcels.geojson", "Demo tax parcels"),
        "zones": (build_trash_zones(zone_rows), "trash_zones.geojson", "Demo trash pickup zones"),
        "drains": (build_drains(lines, local, boundary), "storm_drains.geojson", "Demo storm drains"),
        "hydrants": (build_hydrants(lines, local, boundary), "hydrants.geojson", "Demo fire hydrants"),
        "lights": (build_lights(lines, local, boundary), "streetlights.geojson", "Demo streetlights"),
        "signs": (build_signs(lines, local, boundary), "street_signs.geojson", "Demo street signs"),
    }
    counts = {}
    for key, (feats, fname, title) in layers.items():
        (out / fname).write_text(json.dumps(fc(feats, title), separators=(",", ":")), encoding="utf-8")
        counts[key] = len(feats)
    (out / "manifest.json").write_text(json.dumps(manifest(counts), indent=2, ensure_ascii=False),
                                       encoding="utf-8")
    for key, n in counts.items():
        print(f"{key:9s} {n:6d}")
    print(f"written to {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
